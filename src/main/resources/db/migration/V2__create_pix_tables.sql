CREATE TABLE transacao_pix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    end_to_end_id VARCHAR(100) NOT NULL,
    txid VARCHAR(100),
    valor NUMERIC(19, 2) NOT NULL,
    horario TIMESTAMP WITH TIME ZONE NOT NULL,
    chave VARCHAR(100),
    pagador JSONB,
    info_pagador TEXT,
    devolucoes JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT transacao_pix_end_to_end_id_uk UNIQUE (end_to_end_id),
    CONSTRAINT transacao_pix_valor_ck CHECK (valor >= 0)
);

CREATE INDEX transacao_pix_status_id_idx
    ON transacao_pix (status, id);

CREATE TABLE consolidado_pix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transacao_pix_id BIGINT NOT NULL,
    end_to_end_id VARCHAR(100) NOT NULL,
    tarifa NUMERIC(19, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    consolidated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT consolidado_pix_transacao_uk UNIQUE (transacao_pix_id),
    CONSTRAINT consolidado_pix_end_to_end_id_uk UNIQUE (end_to_end_id),
    CONSTRAINT consolidado_pix_tarifa_ck CHECK (tarifa >= 0),
    CONSTRAINT consolidado_pix_transacao_fk FOREIGN KEY (transacao_pix_id)
        REFERENCES transacao_pix (id)
);

CREATE INDEX consolidado_pix_status_idx
    ON consolidado_pix (status);
